<script setup lang="ts">
import { computed } from 'vue'
import { useWorkbench } from '@/composables/useWorkbench'
import TokenText from '@/components/common/TokenText.vue'
import InfoTip from '@/components/common/InfoTip.vue'
import { exactNumber, formatLogit, formatProb } from '@/utils/format'

const wb = useWorkbench()
const g = wb.generation
const busy = computed(
  () =>
    wb.autoRunning.value ||
    wb.inferenceStatus.value === 'running' ||
    wb.inferenceStatus.value === 'pending',
)
const canAct = computed(
  () => wb.canInfer.value && wb.tokens.value.length > 0 && !wb.invalidTokenIds.value.length,
)
const pick = computed(() => wb.lastPick.value)
const stopTokens = computed(() =>
  wb.stopTokenIds.value.map((id) => ({ id, text: wb.tokenizer.value?.raw[id] ?? '' })),
)
const progress = computed(() =>
  g.maxNewTokens ? (100 * wb.autoGenerated.value) / g.maxNewTokens : 0,
)
const generatedText = computed(() => {
  void wb.historyVersion.value
  if (!wb.autoGenerated.value) return []
  const start = wb.autoStartIndex.value
  return wb.tokens.value.slice(start, start + wb.autoGenerated.value)
})
</script>

<template>
  <section class="panel card" aria-labelledby="gen-title" data-testid="generation-controls">
    <div class="row">
      <h2 id="gen-title">Generate</h2>
      <InfoTip label="Inference vs. token selection">
        <p>
          <strong>Inference</strong> runs the neural network on the exact token sequence and returns
          logits for the next position.
        </p>
        <p>
          <strong>Token selection</strong> (manual pick, sampling or greedy) chooses one token ID,
          appends it, and the network runs again on the longer sequence. That loop is all
          “generation” is.
        </p>
      </InfoTip>
    </div>
    <div class="row">
      <button
        type="button"
        class="btn btn-primary"
        :disabled="!canAct || busy"
        data-testid="sample-one"
        @click="wb.sampleOne()"
      >
        Sample 1 token
      </button>
      <button
        type="button"
        class="btn"
        :disabled="!canAct || busy"
        data-testid="greedy-one"
        @click="wb.greedyOne()"
      >
        Append most likely
      </button>
    </div>
    <p class="small muted">
      Or click <strong>Append</strong> on any row in the candidate table or vocabulary explorer to
      choose a token manually.
    </p>

    <div v-if="pick" class="last card small" data-testid="last-pick" aria-live="polite">
      <div class="row">
        <strong>Last appended:</strong>
        <TokenText
          :text="wb.tokenizer.value?.decoded[pick.tokenId] ?? ''"
          :special="wb.tokenizer.value?.specialIds.includes(pick.tokenId)"
        />
        <code>ID {{ pick.tokenId }}</code>
        <span class="badge">{{ pick.source }}</span>
      </div>
      <div class="row faint">
        <span :title="exactNumber(pick.originalProbability)"
          >original p {{ formatProb(pick.originalProbability) }}</span
        >
        <span :title="exactNumber(pick.adjustedProbability)"
          >adjusted p {{ formatProb(pick.adjustedProbability) }}</span
        >
        <span>logit {{ formatLogit(pick.logit) }}</span>
        <span v-if="pick.uniform !== null" :title="exactNumber(pick.uniform)"
          >u = {{ pick.uniform.toFixed(6) }}</span
        >
        <span>position {{ pick.position }}</span>
      </div>
    </div>

    <fieldset class="auto">
      <legend>Automatic generation</legend>
      <div class="row small">
        <label
          >Max new tokens
          <input
            v-model.number="g.maxNewTokens"
            type="number"
            min="1"
            max="4096"
            class="num"
            data-testid="max-tokens"
        /></label>
        <label class="row"
          ><input v-model="g.stopAtStopTokens" type="checkbox" data-testid="stop-at-eos" /> stop at
          end-of-sequence / end-of-turn</label
        >
      </div>
      <p class="small faint">
        Stop tokens (from generation_config / config):
        <span v-if="!stopTokens.length">none</span>
        <code v-for="t in stopTokens" :key="t.id" class="stop">{{ t.text }} ({{ t.id }})</code>
        — other special tokens do not stop generation.
      </p>
      <div class="row">
        <button
          v-if="!wb.autoRunning.value"
          type="button"
          class="btn btn-primary"
          :disabled="!canAct || busy"
          data-testid="auto-start"
          @click="wb.startAuto()"
        >
          Start
        </button>
        <button
          v-else
          type="button"
          class="btn btn-danger"
          data-testid="auto-stop"
          @click="wb.stopAuto()"
        >
          Stop
        </button>
        <div
          class="bar"
          role="progressbar"
          aria-label="Generation progress"
          :aria-valuenow="wb.autoGenerated.value"
          aria-valuemin="0"
          :aria-valuemax="g.maxNewTokens"
        >
          <div class="fill" :style="{ width: progress + '%' }" />
        </div>
        <span class="small" data-testid="auto-count"
          >{{ wb.autoGenerated.value }} / {{ g.maxNewTokens }}</span
        >
        <span class="small faint" data-testid="auto-tps">{{
          wb.autoTokensPerSecond.value ? wb.autoTokensPerSecond.value.toFixed(2) + ' tok/s' : ''
        }}</span>
      </div>
      <p
        v-if="wb.autoStopReason.value && !wb.autoRunning.value"
        class="small"
        data-testid="auto-stop-reason"
      >
        Stopped: {{ wb.autoStopReason.value }}
      </p>
      <p v-if="generatedText.length" class="small generated" data-testid="auto-generated">
        <span v-for="(id, k) in generatedText" :key="k" class="gtok" :class="{ alt: k % 2 }"
          ><TokenText
            :text="wb.tokenizer.value?.decoded[id] ?? ''"
            :special="wb.tokenizer.value?.specialIds.includes(id)"
        /></span>
      </p>
    </fieldset>
  </section>
</template>

