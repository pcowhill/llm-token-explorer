import { describe, expect, it } from 'vitest'
import GenerationControls from '@/components/sampling/GenerationControls.vue'
import HistoryPanel from '@/components/history/HistoryPanel.vue'
import DiagnosticsPanel from '@/components/diagnostics/DiagnosticsPanel.vue'
import { makeWorkbench, mountWith, settle } from './helpers'
import { Sfc32, seedToState } from '@/sampling/prng'
import { sampleFromAdjusted } from '@/sampling/pipeline'

async function until(cond: () => boolean, ms = 3000) {
  const t0 = Date.now()
  while (!cond()) {
    if (Date.now() - t0 > ms) throw new Error('timeout')
    await settle(1)
  }
}

describe('GenerationControls', () => {
  it('samples exactly one token reproducibly from the seed', async () => {
    const { wb } = await makeWorkbench({ text: 'The' })
    const w = mountWith(GenerationControls, wb)
    await settle()
    const adj = wb.adjusted.value!
    const expectedU = Sfc32.fromSeed(42).nextFloat()
    const expectedId = sampleFromAdjusted(adj, expectedU)
    await w.get('[data-testid="sample-one"]').trigger('click')
    await settle()
    expect(wb.tokens.value).toEqual([8, expectedId])
    expect(w.get('[data-testid="last-pick"]').text()).toContain(`ID ${expectedId}`)
    expect(w.get('[data-testid="last-pick"]').text()).toContain(`u = ${expectedU.toFixed(6)}`)
    w.unmount()
  })

  it('append most likely uses the argmax', async () => {
    const { wb } = await makeWorkbench({ text: 'The the' })
    const w = mountWith(GenerationControls, wb)
    await settle()
    await w.get('[data-testid="greedy-one"]').trigger('click')
    await settle()
    expect(wb.tokens.value.at(-1)).toBe(4)
    w.unmount()
  })

  it('automatic generation respects the maximum and reports progress', async () => {
    const { wb, engine } = await makeWorkbench({ text: 'The' })
    // Remove the stop token's mass so only the max-length condition can stop it
    engine.logitsFn = (ids) => {
      const l = new Float32Array(19).fill(-5)
      l[ids.length % 2 ? 3 : 4] = 5
      l[2] = -Infinity
      return l
    }
    wb.generation.maxNewTokens = 5
    const w = mountWith(GenerationControls, wb)
    await settle()
    await w.get('[data-testid="auto-start"]').trigger('click')
    await until(() => !wb.autoRunning.value)
    expect(wb.tokens.value).toHaveLength(6)
    expect(w.get('[data-testid="auto-count"]').text()).toBe('5 / 5')
    expect(w.get('[data-testid="auto-stop-reason"]').text()).toContain('maximum of 5')
    expect(w.find('[data-testid="auto-generated"]').exists()).toBe(true)
    w.unmount()
  })

  it('stops at the model stop token but not at other special tokens', async () => {
    const { wb, engine } = await makeWorkbench({ text: 'The' })
    let step = 0
    engine.logitsFn = () => {
      const l = new Float32Array(19).fill(-50)
      l[step++ === 0 ? 1 : 2] = 50 // first emit <|im_start|> (special, not stop), then <|im_end|> (stop)
      return l
    }
    await wb.runInference(true)
    wb.generation.maxNewTokens = 10
    const w = mountWith(GenerationControls, wb)
    await settle()
    await w.get('[data-testid="auto-start"]').trigger('click')
    await until(() => !wb.autoRunning.value)
    expect(wb.tokens.value).toEqual([8, 1, 2])
    expect(wb.autoStopReason.value).toContain('Stop token 2')
    w.unmount()
  })

  it('can be stopped by the user', async () => {
    const { wb, engine } = await makeWorkbench({ text: 'The' })
    engine.forwardDelayMs = 20
    // A flat (but not constant: constant logits are rejected as degenerate) distribution.
    engine.logitsFn = () => {
      const l = new Float32Array(19).map((_, i) => (i % 3) / 10)
      l[2] = -Infinity
      return l
    }
    wb.generation.maxNewTokens = 1000
    const w = mountWith(GenerationControls, wb)
    await settle()
    await w.get('[data-testid="auto-start"]').trigger('click')
    await until(() => wb.autoGenerated.value >= 2)
    await w.get('[data-testid="auto-stop"]').trigger('click')
    await until(() => !wb.autoRunning.value)
    expect(wb.autoGenerated.value).toBeLessThan(10)
    expect(wb.autoStopReason.value).toContain('Stopped by user')
    w.unmount()
  })
})

describe('HistoryPanel', () => {
  it('undo, redo and alternate branches preserve exact token IDs', async () => {
    const { wb } = await makeWorkbench({ text: 'The' })
    const w = mountWith(HistoryPanel, wb)
    wb.pickToken(3)
    wb.pickToken(4)
    await settle()
    await w.get('[data-testid="undo"]').trigger('click')
    expect(wb.tokens.value).toEqual([8, 3])
    wb.pickToken(10) // different choice → branch
    await settle()
    expect(w.text()).toContain('Branch 2 of 2')
    await w.get('[data-testid="branch-prev"]').trigger('click')
    expect(wb.tokens.value).toEqual([8, 3, 4])
    await w.get('[data-testid="undo"]').trigger('click')
    await w.get('[data-testid="redo"]').trigger('click')
    expect(wb.tokens.value).toEqual([8, 3, 4])
    expect(w.findAll('[data-testid="history-tree"] li').length).toBeGreaterThanOrEqual(4)
    w.unmount()
  })

  it('exports and re-imports an experiment, restoring tokens, branches and settings', async () => {
    const { wb } = await makeWorkbench({ text: 'The' })
    wb.sampling.temperature = 0.42
    wb.sampling.seed = 1234
    await wb.sampleOne()
    wb.undo()
    wb.pickToken(13)
    await settle()
    const json = wb.exportExperiment()
    const tokens = [...wb.tokens.value]
    const nodes = wb.getTree().nodes.size

    const { wb: wb2 } = await makeWorkbench()
    const w = mountWith(HistoryPanel, wb2)
    const input = w.get('[data-testid="import-input"]')
    Object.defineProperty(input.element, 'files', {
      value: [new File([json], 'exp.json', { type: 'application/json' })],
    })
    await input.trigger('change')
    await settle()
    expect(wb2.tokens.value).toEqual(tokens)
    expect(wb2.getTree().nodes.size).toBe(nodes)
    expect(wb2.sampling.temperature).toBe(0.42)
    expect(wb2.sampling.seed).toBe(1234)
    w.unmount()
  })

  it('rejects invalid experiment files with a clear message', async () => {
    const { wb } = await makeWorkbench({ text: 'The' })
    const w = mountWith(HistoryPanel, wb)
    const input = w.get('[data-testid="import-input"]')
    Object.defineProperty(input.element, 'files', {
      value: [new File(['{"format":"nope"}'], 'bad.json')],
    })
    await input.trigger('change')
    await settle()
    expect(w.get('[data-testid="import-error"]').text()).toContain('Invalid experiment file')
    expect(wb.tokens.value).toEqual([8])
    w.unmount()
  })

  it('warns when importing an experiment created with a different model', async () => {
    const { wb } = await makeWorkbench({ text: 'The' })
    const json = JSON.parse(wb.exportExperiment())
    json.model.identity = 'other-model'
    json.model.displayName = 'Other'
    json.history.nodes.find((n: { id: string }) => n.id === json.history.currentId).tokens = [
      8, 500,
    ]
    const w = mountWith(HistoryPanel, wb)
    const input = w.get('[data-testid="import-input"]')
    Object.defineProperty(input.element, 'files', {
      value: [new File([JSON.stringify(json)], 'x.json')],
    })
    await input.trigger('change')
    await settle()
    const msg = w.get('[data-testid="import-messages"]').text()
    expect(msg).toContain('differs from the loaded model')
    expect(msg).toContain('outside the loaded model')
    expect(wb.invalidTokenIds.value).toEqual([500])
    w.unmount()
  })
})

describe('DiagnosticsPanel', () => {
  it('distinguishes measured, estimated, configured and unavailable metrics', async () => {
    const { wb } = await makeWorkbench({ text: 'The' })
    const w = mountWith(DiagnosticsPanel, wb)
    await settle()
    const text = w.text()
    expect(text).toContain('Neural network inference')
    expect(text).toContain('Not exposed by WebGPU')
    expect(text).toContain('measured')
    expect(text).toContain('estimate')
    expect(text).toContain('unavailable')
    expect(text).toContain('[1, 1, 19] float32')
    w.unmount()
  })

  it('stale results never overwrite a newer context', async () => {
    const { wb, engine } = await makeWorkbench({ text: 'The' })
    engine.forwardDelayMs = 30
    wb.setTokens([8, 3], 'a')
    await new Promise((r) => setTimeout(r, 5))
    wb.setTokens([8, 4], 'b')
    await new Promise((r) => setTimeout(r, 120))
    await settle()
    expect(wb.result.value?.tokens).toEqual([8, 4])
    expect(wb.resultIsCurrent.value).toBe(true)
    void seedToState
  })
})

describe('store race conditions', () => {
  it('two concurrent sample requests append only one token', async () => {
    const { wb, engine } = await makeWorkbench({ text: 'The' })
    engine.forwardDelayMs = 20
    wb.setTokens([8, 3], 'x')
    const [a, b] = await Promise.all([wb.sampleOne(), wb.sampleOne()])
    await settle()
    expect([a, b].filter((x) => x !== null)).toHaveLength(1)
    expect(wb.tokens.value).toHaveLength(3)
  })

  it('importing an experiment keeps its saved generator state', async () => {
    const { wb } = await makeWorkbench({ text: 'The' })
    wb.resetSeed(777)
    await wb.sampleOne()
    await settle()
    const saved = [...wb.prng.value]
    const json = wb.exportExperiment()
    const { wb: wb2 } = await makeWorkbench()
    wb2.importExperiment(json)
    await settle()
    expect([...wb2.prng.value]).toEqual(saved)
    expect(wb2.sampling.seed).toBe(777)
  })

  it('a pending text re-tokenization does not undo a later undo', async () => {
    const { wb, engine } = await makeWorkbench({ text: 'The' })
    wb.pickToken(3)
    await settle()
    // A busy worker answers decode requests late, so the typed draft is still pending.
    engine.decodeDelayMs = 100
    wb.setText('The cat sat')
    wb.undo()
    await new Promise((r) => setTimeout(r, 300))
    await settle()
    expect(wb.tokens.value).toEqual([8])
    expect(wb.getTree().nodes.size).toBe(3) // root, "The", "The the" — no stray edit node
  })

  it('navigating back restores a generator state that matches the shown seed', async () => {
    const { wb } = await makeWorkbench({ text: 'The' })
    wb.resetSeed(5)
    const at = [...wb.prng.value]
    await wb.sampleOne()
    await settle()
    wb.undo()
    expect(wb.sampling.seed).toBe(5)
    expect([...wb.prng.value]).toEqual(at)
  })
})
